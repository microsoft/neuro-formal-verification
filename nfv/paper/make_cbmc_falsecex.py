"""Triage of the CBMC arm's false counterexamples (counterexamples on correct references).

The set of false counterexamples and every count below are derived from
nfv/results/cbmc_theory.jsonl.  The *cause* of each one is a manual reading of
the entry's stage-1b precondition against the documented input assumptions in
nfv/data/input_assumptions.json, and of the failing CBMC properties in
cex_diagnostics; that reading is recorded in CAUSES and the generator asserts
it covers exactly the entries the results file reports, so the classification
cannot silently drift away from the run.

Causes:
  documented   the docstring states or plainly implies a constraint that the
               synthesised precondition omits.
  undocumented the docstring states no constraint, so the precondition is empty,
               yet Python itself rejects the witness.
  bound        the precondition is faithful, but an unwinding assertion inside
               the precondition function fails, so the witness was never shown
               to be admissible.
  translation  the precondition is not at fault; the defect is in the
               translated body or goal.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
RESULTS = ROOT / "nfv" / "results" / "cbmc_theory.jsonl"
OUT = pathlib.Path(__file__).resolve().parent / "tables" / "cbmc_falsecex.tex"

CAUSES = {
    # entry_id                            cause,          missing assumption
    "HumanEval_1__r2__reference": ("documented", "groups are balanced and not nested"),
    "HumanEval_115__r0__reference": ("documented", "a rectangular grid of 0s and 1s"),
    "HumanEval_67__r0__reference": ("documented", "the ``N apples and M oranges'' format"),
    "HumanEval_153__r1__reference": ("documented", "a non-empty extension list"),
    "HumanEval_49__r1__reference": ("undocumented", "p > 0 and n >= 0"),
    "HumanEval_59__r1__reference": ("bound", ""),
    "HumanEval_17__r2__reference": ("translation", ""),
}


def main() -> None:
    rows = [json.loads(l) for l in RESULTS.read_text(encoding="utf-8").splitlines() if l.strip()]
    false_cex = {r["entry_id"] for r in rows if r["prediction"] == "incorrect" and r["label"] == "correct"}
    assert false_cex == set(CAUSES), (
        f"triage out of date: only in results {sorted(false_cex - set(CAUSES))}, "
        f"only in CAUSES {sorted(set(CAUSES) - false_cex)}"
    )

    by = {}
    for entry, (cause, _) in CAUSES.items():
        by.setdefault(cause, []).append(entry)

    # every false counterexample whose (truncated) property list still shows a
    # failing property must fail the goal assertion, not a memory-safety or
    # overflow property, or the cause analysis above is about the wrong thing.
    goal_only = 0
    with_fails = 0
    for r in rows:
        if r["entry_id"] not in false_cex:
            continue
        fails = [l for l in (r.get("cex_diagnostics") or "").splitlines() if "FAILURE" in l]
        if not fails:
            continue
        with_fails += 1
        if all("nfv-goal" in l or "unwinding assertion" in l for l in fails):
            goal_only += 1
    assert goal_only == with_fails, (
        "a false counterexample now fails a property other than the goal; "
        "the prose in Section 4 says none does"
    )

    n_pre = len(by.get("documented", [])) + len(by.get("undocumented", []))

    # the arm's headline refutation numbers, from the same file, so that the
    # precision quoted next to the recall is the precision of these very rows.
    claims = [r for r in rows if r["prediction"] == "incorrect"]
    good = [r for r in claims if r["label"] == "incorrect"]
    buggy = [r for r in rows if r["label"] == "incorrect"]
    assert len(claims) == len(good) + len(false_cex)

    lines = [
        "% generated by nfv/paper/make_cbmc_falsecex.py -- do not edit",
        f"\\newcommand{{\\cbmcfpall}}{{{len(false_cex)}}}",
        f"\\newcommand{{\\cbmcfppre}}{{{n_pre}}}",
        f"\\newcommand{{\\cbmcfpdoc}}{{{len(by.get('documented', []))}}}",
        f"\\newcommand{{\\cbmcfpundoc}}{{{len(by.get('undocumented', []))}}}",
        f"\\newcommand{{\\cbmcfpbound}}{{{len(by.get('bound', []))}}}",
        f"\\newcommand{{\\cbmcfptrans}}{{{len(by.get('translation', []))}}}",
        f"\\newcommand{{\\cbmcfpgoalonly}}{{{goal_only}}}",
        f"\\newcommand{{\\cbmcfpwithfails}}{{{with_fails}}}",
        f"\\newcommand{{\\cbmccexclaims}}{{{len(claims)}}}",
        f"\\newcommand{{\\cbmccexgood}}{{{len(good)}}}",
        f"\\newcommand{{\\cbmccexprec}}{{{100 * len(good) / len(claims):.0f}}}",
        f"\\newcommand{{\\cbmccexrec}}{{{100 * len(good) / len(buggy):.0f}}}",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
