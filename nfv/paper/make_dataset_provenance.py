"""Numbers for the Dataset section's construction pipeline.

The corpus is not simply "the nl2postcond benchmark". Two filters of our own sit
between that benchmark and the 103 tasks reported here, and an earlier draft of
the paper claimed the opposite ("we apply no filter of our own"), which is the
kind of statement a reader is entitled to check. So every count in the Dataset
section is emitted from the stage artefacts themselves rather than typed:

  S1  nl2post/nl2post_dataset.json          reference + mutant per task
  S2  results/nl2post_spec_validation.json  agentic test generator over the
      results/nl2post_verified_subset.json  references, and what survived it
  S3  nfv/data/nl2post_safe.json            after dropping type-only specs

All four files are tracked in git, so this script is reproducible by anyone with
the repository -- unlike the run artefacts, which are not shipped.

The last block is the one that matters for Section~\\ref{sec:analysis}: it checks
which of the entries whose label we later dispute were seen by the S2 test
generator, and what it concluded about them. Every one of them passed. That is
reported in the paper as a result rather than an embarrassment -- a proof-based
method found specification violations that 100 generated tests per task missed
-- so it must be recomputed on every build rather than remembered.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLES = Path(__file__).resolve().parent / "tables"

S1 = ROOT / "paper/data/upstream/nl2post/nl2post_dataset.json"
S2_LOG = ROOT / "paper/data/upstream/results/nl2post_spec_validation.json"
S2_OUT = ROOT / "paper/data/upstream/results/nl2post_verified_subset.json"
S3 = ROOT / "nfv/data/nl2post_safe.json"

# The entries Section 5 disputes or declines to classify. Declared here so the
# claim "the test generator passed all of them" is checked, not asserted.
DISPUTED = {
    "HumanEval/11", "HumanEval/20", "HumanEval/64",   # references we call incorrect
    "HumanEval/116",                                   # mutant we call correct
    "HumanEval/49", "HumanEval/79",                    # undetermined
}


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def main() -> int:
    s1 = load(S1)
    log = load(S2_LOG)
    sub = load(S2_OUT)
    s3 = load(S3)

    # --- S1: one reference and one mutant per task -------------------------
    s1_entries, s1_pairs = s1["total"], s1["num_problems"]
    assert s1_entries == 2 * s1_pairs, (s1_entries, s1_pairs)

    # --- S2: the agentic test generator ------------------------------------
    cfg, summary = log["config"], log["summary"]
    tested = len(log["results"])
    assert tested == s1_pairs, f"S2 saw {tested} tasks, S1 has {s1_pairs}"
    passed = summary["pass"]
    spec_fails = summary["spec_fails"]
    # Anything that is neither a pass nor a demonstrated violation was dropped
    # for want of a confirmation, not for failing -- a distinction the paper
    # makes, so compute it rather than lumping it in with the violations.
    unconfirmed = tested - passed - spec_fails
    s2_pairs = len({r.get("task_id") for r in sub})
    assert s2_pairs == passed, f"subset has {s2_pairs} tasks, {passed} passed"
    assert len(sub) == 2 * s2_pairs

    # --- S3: drop specifications a return type already guarantees ----------
    s3_entries, s3_pairs = s3["total"], len({e["task_id"] for e in s3["entries"]})
    assert s3_entries == 2 * s3_pairs
    assert s3["num_correct"] == s3["num_incorrect"] == s3_pairs
    type_only = s2_pairs - s3_pairs

    # --- what the generator concluded about the entries we later dispute ----
    status = {r.get("task_id"): r.get("status") for r in log["results"]}
    corpus = {e["task_id"] for e in s3["entries"]}
    missing = DISPUTED - corpus
    assert not missing, f"disputed entries absent from the corpus: {missing}"
    seen = {t: status.get(t) for t in sorted(DISPUTED)}
    unseen = [t for t, s in seen.items() if s is None]
    assert not unseen, f"disputed entries the S2 generator never saw: {unseen}"
    cleared = [t for t, s in seen.items() if s == "pass"]

    m = {
        "dsonepairs": s1_pairs,
        "dsoneentries": s1_entries,
        "dsgenmodel": str(cfg["model"]),
        "dsgentests": cfg["num_tests"],
        "dstested": tested,
        "dspassed": passed,
        "dsspecfails": spec_fails,
        "dsunconfirmed": unconfirmed,
        "dstwopairs": s2_pairs,
        "dstwoentries": len(sub),
        "dstypeonly": type_only,
        "dspairs": s3_pairs,
        "dsentries": s3_entries,
        "dsdisputed": len(DISPUTED),
        "dsdisputedcleared": len(cleared),
    }
    lines = ["% generated by nfv/paper/make_dataset_provenance.py -- do not edit by hand"]
    bad_names = sorted(k for k in m if not k.isalpha())
    if bad_names:
        raise SystemExit(f"macro names must be letters only: {bad_names}")
    for k, v in m.items():
        lines.append(rf"\newcommand{{\{k}}}{{{v}}}")
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / "dataset_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote dataset_numbers.tex:", m)
    print("S2 verdicts on the disputed entries:", seen)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
