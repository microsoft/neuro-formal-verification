"""Emit tables/cbmc_clean.tex: how unsound CBMC's two clean-run buckets are.

The arm abstains on every clean run, and Section 4 says so. This script prices
that decision instead of asserting it. Both buckets -- the one whose unwinding
assertions passed and the one whose did not -- are split against the benchmark's
labels, so the prose can name how many *known-buggy* programs sit inside each.

The bound-exhausted bucket is the interesting one. It fails for a reason
independent of the loop bound: `nfv/backends/cbmc.py` bounds the *inputs*
(`NFV_LEN_MAX` on lengths, numeric bounds, a character range), so exhausting the
unwinding establishes only that no failing execution exists inside a box we drew
ourselves. The buggy entries in that bucket are the direct evidence.

The `exhausted` predicate is deliberately the same condition as
`cbmc_exhausted()` in make_compare_tables.py, which drives the counterfactual
verification cells of the backend comparison; a divergence would make this
paragraph and that table disagree about the same entries.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUN = ROOT / "nfv" / "results" / "cbmc_theory.jsonl"
OUT = ROOT / "nfv" / "paper" / "tables" / "cbmc_clean.tex"

CLEAN = "no violating execution found within the unwinding bound"
PARTIAL = "the bound did not exhaust every loop"
UB = "undefined behaviour on the path to the assertion"


def bucket(r: dict) -> str | None:
    reason = str(r.get("reason") or "")
    if r.get("prediction") != "abstain" or CLEAN not in reason or UB in reason:
        return None
    return "partial" if PARTIAL in reason else "exhausted"


def main() -> None:
    rows = [json.loads(l) for l in RUN.read_text(encoding="utf-8").splitlines() if l.strip()]

    counts = {"exhausted": [0, 0], "partial": [0, 0]}  # [correct, buggy]
    for r in rows:
        b = bucket(r)
        if b is None:
            continue
        counts[b][0 if r.get("label") == "correct" else 1] += 1

    ex_ok, ex_bad = counts["exhausted"]
    pa_ok, pa_bad = counts["partial"]
    ex, pa = ex_ok + ex_bad, pa_ok + pa_bad
    both_ok, both = ex_ok + pa_ok, ex + pa

    # A clean run is only worth reporting as *unsound* if it actually misses
    # bugs; if this ever hits zero the prose in Section 4 must be rewritten to
    # rest on the bounded input domain alone.
    assert ex_bad > 0, "no buggy program survives a bound-exhausted clean run"

    lines = [
        "% generated by nfv/paper/make_cbmc_clean.py -- do not edit",
        f"\\newcommand{{\\cbmccleanall}}{{{ex}}}",
        f"\\newcommand{{\\cbmccleangood}}{{{ex_ok}}}",
        f"\\newcommand{{\\cbmccleanbuggy}}{{{ex_bad}}}",
        f"\\newcommand{{\\cbmccleanprec}}{{{100 * ex_ok / ex:.0f}}}",
        f"\\newcommand{{\\cbmcpartall}}{{{pa}}}",
        f"\\newcommand{{\\cbmcpartgood}}{{{pa_ok}}}",
        f"\\newcommand{{\\cbmcpartbuggy}}{{{pa_bad}}}",
        f"\\newcommand{{\\cbmcbothall}}{{{both}}}",
        f"\\newcommand{{\\cbmcbothprec}}{{{100 * both_ok / both:.0f}}}",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
