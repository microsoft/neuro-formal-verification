"""Generate tables/judge_numbers.tex from nfv/results/judge.jsonl (Baseline C)."""
import collections
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "nfv" / "results" / "judge.jsonl"
OUT = pathlib.Path(__file__).resolve().parent / "tables" / "judge_numbers.tex"


def load():
    rows = {}
    for line in SRC.read_text(encoding="utf-8").splitlines():
        if line.strip():
            r = json.loads(line)
            rows[r["entry_id"]] = r
    return list(rows.values())


def pct(n, d):
    return round(100 * n / d) if d else 0


def main():
    rows = load()
    total = len(rows)
    correct = [r for r in rows if r["label"] == "correct"]
    buggy = [r for r in rows if r["label"] == "incorrect"]
    assert len(correct) == len(buggy), (len(correct), len(buggy))

    said_incorrect = [r for r in rows if r["prediction"] == "incorrect"]
    said_correct = [r for r in rows if r["prediction"] == "correct"]
    unknown = [r for r in rows if r["prediction"] not in ("correct", "incorrect")]
    committed = len(said_incorrect) + len(said_correct)

    wrong = [r for r in rows if r["prediction"] in ("correct", "incorrect")
             and r["prediction"] != r["label"]]
    caught = [r for r in buggy if r["prediction"] == "incorrect"]
    falsealarm = [r for r in correct if r["prediction"] == "incorrect"]
    missed = [r for r in buggy if r["prediction"] == "correct"]

    by_task = collections.defaultdict(dict)
    for r in rows:
        by_task[r["task_id"]][r["label"]] = r["prediction"]
    discriminated = sum(
        1 for t, d in by_task.items()
        if d.get("correct") == "correct" and d.get("incorrect") == "incorrect"
    )

    m = {
        "jdgtotal": total,
        "jdgcommitted": committed,
        "jdgunknown": len(unknown),
        "jdgsaidbad": len(said_incorrect),
        "jdgsaidbadpct": pct(len(said_incorrect), total),
        "jdgwrong": len(wrong),
        "jdgwrongpct": pct(len(wrong), total),
        "jdgprec": pct(len(caught), len(said_incorrect)),
        "jdgcaught": len(caught),
        "jdgbuggy": len(buggy),
        "jdgfalsealarm": len(falsealarm),
        "jdgmissed": len(missed),
        "jdgpairs": len(by_task),
        "jdgdiscriminated": discriminated,
        # The judge never abstains, so every entry gets a verdict and its
        # overall precision, recall and accuracy are the same number. The
        # paper quotes it against the pipeline row of Table 3.
        "jdgallgood": committed - len(wrong),
        "jdgallprec": pct(committed - len(wrong), committed),
    }
    body = "% GENERATED by nfv/paper/make_judge_numbers.py -- do not edit.\n"
    body += "".join("\\newcommand{\\%s}{%s}\n" % (k, v) for k, v in m.items())
    OUT.write_text(body, encoding="utf-8")
    print(body)


if __name__ == "__main__":
    main()
