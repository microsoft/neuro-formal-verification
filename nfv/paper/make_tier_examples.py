"""One example program per library tier, taken verbatim from the dataset.

The tiers are defined by what a program forces the model to axiomatise, which is
an operational definition and therefore easy to state and hard to picture. These
examples make the ladder concrete: each is the SHORTEST correct entry in its
tier, so the differences between them are differences in what the environment
demands rather than in program size.

Selection is mechanical -- shortest correct entry, ties broken by task id -- so
no example is chosen to flatter a result, and the source is copied from the
dataset rather than retyped.
"""
from __future__ import annotations

import json
from pathlib import Path

from nfv.data.build_subset import (DATASET, _TRIVIAL, _calls_used,
                                   higher_order_tasks, tier_label)

TABLES = Path(__file__).resolve().parent / "tables"

TIERS = ("0", "1", "2a", "2b", "3")

WHY = {
    "0": "Nothing outside the program has to be described, so the model's "
         "trusted base can be empty.",
    "1": "Each call here is one self-contained, total function whose meaning "
         "the model can state in a line.",
    "2a": "A faithful specification has to relate whole collections --- what "
          "the result contains, and in what order --- rather than give a "
          "single value.",
    "2b": "The specification must quantify over an argument whose body it "
          "cannot see, which is a different demand from describing a "
          "collection.",
    "3": "The boundary is not the model's to choose: it must axiomatise a "
         "surface defined elsewhere, and any axiom it writes about that "
         "surface is assumed, not checked.",
}

# L3 is reached by an import OR by a call outside every modelled set, so the
# example is picked from the tasks that actually import, which is the case the
# tier is named for.
L3_MUST_IMPORT = True


def main() -> int:
    payload = json.loads(DATASET.read_text(encoding="utf-8"))
    used = _calls_used()
    hof = higher_order_tasks()
    tier_of = {t: tier_label(t, c, hof) for t, c in used.items()}

    best: dict[str, tuple[int, str, str]] = {}
    for e in payload["entries"]:
        if e["label"] != "correct":
            continue
        tid = e["task_id"]
        k = tier_of[tid]
        if k == "3" and L3_MUST_IMPORT:
            if not any(c.startswith("import ") for c in used[tid] - _TRIVIAL):
                continue
        n = len(e["code"].splitlines())
        cand = (n, tid, e["code"].strip())
        if k not in best or cand < best[k]:
            best[k] = cand

    missing = [k for k in TIERS if k not in best]
    if missing:
        raise SystemExit(f"no example found for tier(s) {missing}")

    blocks = []
    for k in TIERS:
        _n, tid, code = best[k]
        # What the program actually touches, read off the same source analysis
        # that assigns the tier, so the description cannot drift from the code.
        rest = sorted(used[tid] - _TRIVIAL)
        if rest:
            names = ", ".join(rf"\texttt{{{c.replace('import ', 'import ')}}}"
                              for c in rest)
            touches = f"Beyond arithmetic, indexing and control flow it uses {names}."
        else:
            touches = ("It uses nothing beyond arithmetic, indexing and control "
                       "flow.")
        blocks.append(
            rf"""\paragraph{{L{k} --- {tid}.}} {touches} {WHY[k]}
\begin{{lstlisting}}[language=Python]
{code}
\end{{lstlisting}}""")

    out = ("% generated by nfv/paper/make_tier_examples.py -- do not edit by hand\n"
           + "\n\n".join(blocks) + "\n")
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / "tierexamples.tex").write_text(out, encoding="utf-8")
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
